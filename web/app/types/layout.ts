/**
 * Модель раскладки группы материалов на стартовой странице.
 *
 * Раскладка описывается матрицей областей: строка — ряд сетки, символ — одна из
 * двенадцати колонок, точка — намеренная пустота. Вся остальная геометрия
 * (порядок слотов, вместимость, разделители) выводится из матрицы, а не
 * задаётся отдельными таблицами.
 */

/** Четыре канонических варианта карточки. Имена менять нельзя: на них ссылаются спецификации. */
export type CardVariant = "lede" | "large" | "small" | "rank"

/** Композиция внутри варианта: изображение сбоку или над текстом. */
export type SlotMedia = "beside" | "above"

export interface SlotSpec {
  /** Буква слота в матрице `cells`. */
  key: string
  variant: CardVariant
  media?: SlotMedia
  /**
   * Ведущий слот группы: заголовок поднимается на ступень шкалы.
   * Ставится там, где изображение заметно крупнее соседних — крупная
   * картинка с рядовым заголовком читается как подпись под фотографией.
   */
  scale?: "lead"
}

/** Признаки раскладки. По ним проверяется, что соседние группы не читаются одинаково. */
export interface LayoutTraits {
  /** Где сидит масса группы. */
  anchor: "left" | "center" | "right"
  /** Форма главной ячейки. */
  dominant: "wide" | "tall" | "none"
  /** Раскладка-нарушение. Такая на странице допускается только одна. */
  accent?: boolean
}

export interface GroupLayout {
  id: string
  /** Строки матрицы, каждая ровно `GRID_COLUMNS` символов. */
  cells: string[]
  /** Порядок слотов = порядок материалов. Вместимость группы — длина массива. */
  slots: SlotSpec[]
  /** Число колонок на средних экранах и спаны слотов. Без него выводится умолчание. */
  md?: {
    cols: number
    spans?: Record<string, number>
  }
  traits: LayoutTraits
}

/** Разделители ячейки, выведенные из матрицы. */
export interface SlotRules {
  right: boolean
}

export const GRID_COLUMNS = 12
