-- T-126: имя аккаунта не выводится из локальной части e-mail.
-- Регистрация писала в `name` часть адреса до «@» (ADR-0018 п. 3 это запрещает: e-mail не
-- попадает ни в хэндл, ни в имя, ни в адреса страниц; журнал §25.4). Резолвер регистрации
-- больше так не делает, а уже заведённые аккаунты чистит эта миграция: имя, равное локальной
-- части собственного адреса, становится пустым. Пустое имя публично показывается хэндлом,
-- своё имя владелец аккаунта задаёт в профиле до первой публикации.
-- Сравнение без учёта регистра: «Ivan.Petrov» для ivan.petrov@example.test — тот же адрес,
-- записанный другим регистром, а не самостоятельно выбранное имя.
UPDATE "users"
SET "name" = ''
WHERE "name" <> ''
  AND lower("name") = lower(split_part("email", '@', 1));
