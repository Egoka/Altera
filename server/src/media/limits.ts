// Числовые пороги конвейера медиа. Журнал §33 п. 3: параметры предлагает архитектор в проходе
// конвейера, утверждает владелец, и до утверждения загрузка пользователям не открывается. Поэтому
// все числа собраны здесь одним списком с пометкой `[ДОПУЩЕНИЕ]` — заменить их после решения
// владельца нужно в одном файле, а не по коду.

/** `[ДОПУЩЕНИЕ]` Размер файла: 20 МБ (ADR-0008 п. 6, `upload-pipeline.md` п. 3). */
export const MAX_UPLOAD_BYTES = 20 * 1024 * 1024

/**
 * `[ДОПУЩЕНИЕ]` Предел числа пикселей. Заметка владельца требует защиты мастера от чрезмерного
 * разрешения, числа не называя. Предложение архитектора — 50 Мп: это вдвое больше самой большой
 * ходовой фотокамеры потребительского класса и на порядок больше крупнейшего варианта ADR-0030
 * (2000 px), а декодирование такого кадра остаётся в пределах памяти процесса API.
 */
export const MAX_IMAGE_PIXELS = 50_000_000

/** `[ДОПУЩЕНИЕ]` Минимальная сторона: изображение меньше этого — не медиа, а артефакт загрузки. */
export const MIN_IMAGE_SIDE = 16

/**
 * `[ДОПУЩЕНИЕ]` Качество перекодирования мастера. Мастер — постоянный оригинал и источник всех
 * вариантов (§29.2), поэтому значения выше обычных для выдачи: сжатие выдачи — шаг вариантов
 * (T-064), а не мастера. PNG остаётся без потерь.
 */
export const MASTER_ENCODE_QUALITY = {
  jpeg: 92,
  webp: 95,
  avif: 80
} as const

/**
 * `[ДОПУЩЕНИЕ]` Временная матрица ширин: 480, 960, 1440, 2000 из ADR-0030 (журнал §33 п. 2). До
 * конца прохода конвейера медиа точки останова не уточняются, после — заменяются скриптом
 * пересчёта вариантов (`image-variants.md` §2 п. 1, п. 6).
 */
export const VARIANT_WIDTHS = [480, 960, 1440, 2000] as const

/**
 * Ширина размытого заполнителя. Заметка владельца п. 2 называет «очень маленькую миниатюру /
 * размытый placeholder, начиная примерно с 48 × 48» — это единственное число набора, которое
 * владелец назвал сам.
 */
export const PLACEHOLDER_WIDTH = 48

/** `[ДОПУЩЕНИЕ]` Радиус размытия заполнителя: LQIP должен читаться пятном, а не деталями. */
export const PLACEHOLDER_BLUR = 4

/**
 * `[ДОПУЩЕНИЕ]` Качество кодирования публичных вариантов. Ниже мастера: вариант — выдача, а не
 * источник (§29.2). AVIF при равном качестве картинки кодируется меньшим числом, чем WebP,
 * поэтому значения разные. Предложение архитектора до утверждения владельцем (журнал §33 п. 3).
 */
export const VARIANT_ENCODE_QUALITY = {
  avif: 50,
  webp: 75
} as const

/** `[ДОПУЩЕНИЕ]` Качество заполнителя: он всё равно размыт, вес важнее точности. */
export const PLACEHOLDER_QUALITY = 40
