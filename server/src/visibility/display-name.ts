/**
 * Публичное имя аккаунта. Имя задаёт сам пользователь (`docs/spec/30-account/reader/profile-edit.md`),
 * а до этого его нет: регистрация имени не придумывает и локальную часть e-mail в него не пишет
 * (ADR-0018 п. 3, журнал §25.4, T-126). Наружу вместо пустого имени уходит хэндл — публичная
 * страница автора и ленты показывают опознаваемую строку, а не пробел и не адрес почты.
 */
export const publicDisplayName = (name: string | null | undefined, handle: string): string =>
  name?.trim() ? name : handle

/** Имя нового аккаунта до первой правки профиля: пустая строка, а не производное от e-mail. */
export const EMPTY_ACCOUNT_NAME = ""
