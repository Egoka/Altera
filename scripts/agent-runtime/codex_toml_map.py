def _secret_key(key):
    lowered = key.lower()
    return any(part in lowered for part in _SECRET_PARTS)


def _render_block(ready):
    lines = [BEGIN_MARKER]
    first = True
    for name in ("context7", "playwright", "trace"):
        if name not in ready:
            continue
        if not first:
            lines.append("")
        first = False
        lines.append("[mcp_servers.%s]" % name)
        if name == "context7":
            lines.extend(("experimental_use_rmcp_client = true", 'url = "https://mcp.context7.com/mcp"'))
        elif name == "playwright":
            lines.extend(('command = "/usr/bin/env"', 'args = ' + json.dumps(PLAYWRIGHT_VECTOR[1:], separators=(",", ":"))))
        else:
            lines.extend(('command = "/usr/local/bin/trace-mcp"', 'args = ["serve"]'))
    lines.append(END_MARKER)
    return ("\n".join(lines) + "\n").encode()


def build_mapping(data, mapping_policy_version, required_servers=(), *, playwright=None):
    """Разобрать managed TOML; optional receipt читается только через строгий validator."""
    if not isinstance(mapping_policy_version, str) or not _POLICY_VERSION.fullmatch(mapping_policy_version):
        _fail("mapping_policy_invalid")
    if (not isinstance(required_servers, (tuple, list)) or
            any(not isinstance(name, str) or name not in ("context7", "playwright", "trace")
                for name in required_servers) or
            len(required_servers) != len(set(required_servers))):
        _fail("required_roster_invalid")

    selected_policy = mapping_policy_version == "codex-mcp-map-selected-v2"
    if selected_policy and not required_servers:
        _fail("required_roster_invalid")
    attestation = read_playwright_attestation(playwright) if playwright is not None else None
    tables = _parse_managed(data, selected_policy=selected_policy)
    rows = _server_rows()
    catalog = {
        "schema": SCHEMA,
        "managed_state": "unresolved" if tables is None else ("explicit_empty" if not tables else "explicit_nonempty"),
        "descriptor_valid": True,
        "unknown_servers_present": False,
        "unknown_fields_present": False,
        "secret_fields_present": False,
        "servers": rows,
        "managed_mapping_verified": False,
    }
    failure = None
    if selected_policy:
        catalog.update(selection=sorted(required_servers), excluded_server_count=0)
    path_map = {}
    ready = set()
    if tables is None:
        failure = "managed_config_absent"
    else:
        by_name = {row["name"]: row for row in rows}
        for name, fields in tables.items():
            if selected_policy and name not in required_servers:
                catalog["excluded_server_count"] += 1
                continue
            if name not in by_name:
                catalog["unknown_servers_present"] = True
                catalog["unknown_fields_present"] = bool(fields) or catalog["unknown_fields_present"]
                catalog["secret_fields_present"] = (catalog["secret_fields_present"] or
                                                     any(_secret_key(key) for key in fields))
                failure = "unverified_managed_config"
                continue
            row = by_name[name]
            row["present"] = True
            unknown = False
            if name == "context7":
                expected = {"experimental_use_rmcp_client", "url"}
                valid = (set(fields) == expected and fields.get("experimental_use_rmcp_client") is True and
                         fields.get("url") == "https://mcp.context7.com/mcp")
                shape = "context7_public_mcp"
            elif name == "trace":
                expected = {"command", "args"}
                command = fields.get("command")
                arguments = fields.get("args")
                valid = (set(fields) == expected and isinstance(command, str) and
                         command in _TRACE_COMMANDS and isinstance(arguments, list) and
                         all(isinstance(argument, str) for argument in arguments) and
                         arguments == ["serve"])
                shape = "trace_serve"
            else:
                expected = {"command", "args"}
                command = fields.get("command")
                arguments = fields.get("args")
                valid = (set(fields) == expected and isinstance(command, str) and command == "npx" and
                         isinstance(arguments, list) and
                         all(isinstance(argument, str) for argument in arguments) and
                         tuple(arguments) in _PLAYWRIGHT_ARGS)
                shape = "playwright_dynamic_npx"
            if set(fields) - expected:
                unknown = True
                catalog["unknown_fields_present"] = True
                catalog["secret_fields_present"] = (catalog["secret_fields_present"] or
                                                     any(_secret_key(key) for key in set(fields) - expected))
            if valid and name != "playwright":
                row.update(shape=shape, mapping_ready=True)
                ready.add(name)
                if name == "trace":
                    path_map[fields["command"]] = "/usr/local/bin/trace-mcp"
            elif valid and attestation is not None:
                row.update(shape="playwright_static_0_0_80", mapping_ready=True)
                ready.add(name)
            elif valid:
                row.update(shape=shape, mapping_ready=False)
                failure = failure or "mapping_not_ready"
            else:
                row.update(shape="unverified", mapping_ready=False)
                failure = "unverified_managed_config"
                if unknown:
                    catalog["unknown_fields_present"] = True

        if failure is None:
            if any(not by_name[name]["present"] or not by_name[name]["mapping_ready"] for name in required_servers):
                failure = "required_server_missing"
            else:
                catalog["managed_mapping_verified"] = True

    catalog_json = _canonical_json(catalog)
    block = _render_block(ready) if failure is None else None
    return {
        "catalog": catalog,
        "catalog_json": catalog_json,
        "catalog_sha256": _digest(catalog_json),
        "mapping_digest": _digest(catalog_json + b"\x00" + mapping_policy_version.encode()),
        "path_map": path_map,
        "policy_block": block,
        "failure": failure,
    }


def _identity(info):
    return (info.st_dev, info.st_ino, stat.S_IFMT(info.st_mode), stat.S_IMODE(info.st_mode),
            info.st_uid, info.st_gid, info.st_nlink, info.st_size, info.st_mtime_ns, info.st_ctime_ns)


def _inode_identity(info):
    return (info.st_dev, info.st_ino, stat.S_IFMT(info.st_mode), stat.S_IMODE(info.st_mode),
            info.st_uid, info.st_gid, info.st_size)


def _read_all(fd):
    chunks = []
    total = 0
    while True:
        try:
            chunk = os.read(fd, min(8192, MAX_CONFIG_BYTES + 1 - total))
        except BlockingIOError:
            _fail("config_metadata_invalid")
        if not chunk:
            break
        chunks.append(chunk)
        total += len(chunk)
        if total > MAX_CONFIG_BYTES:
            _fail("input_bound_exceeded")
    return b"".join(chunks)


def _validate_descriptor(record, workspace_root, expected_cwd, expected_uid):
    if not isinstance(expected_uid, int) or isinstance(expected_uid, bool) or expected_uid < 0:
        _fail("descriptor_invalid")
    if not isinstance(record, dict) or record.get("binary_sha256") != D2_BINARY_SHA256:
        _fail("descriptor_invalid")
    descriptor = record.get("descriptor")
    if not isinstance(descriptor, dict):
        _fail("descriptor_invalid")
    expected = {
        "source_sha256": D2_SOURCE_SHA256,
        "build_sha256": D2_BUILD_SHA256,
        "read_status": "lexical_candidate",
        "canonical_identity": "not_checked",
        "task_acceptance": "not_checked",
        "cwd_matches_expected": True,
    }
    if any(descriptor.get(key) != value for key, value in expected.items()):
        _fail("descriptor_invalid")
    if not isinstance(descriptor.get("argc"), int) or isinstance(descriptor.get("argc"), bool):
        _fail("descriptor_invalid")
    for value in (workspace_root, expected_cwd):
        if not isinstance(value, str) or not value.startswith("/") or os.path.normpath(value) != value:
            _fail("descriptor_invalid")
    if os.getcwd() != expected_cwd:
        _fail("descriptor_invalid")
    candidate = descriptor.get("candidate_path")
    try:
        candidate_size = len(candidate.encode("utf-8")) if isinstance(candidate, str) else None
    except UnicodeEncodeError:
        _fail("descriptor_invalid")
    if candidate_size is None or candidate_size > 1024:
        _fail("descriptor_invalid")
    pattern = re.escape(workspace_root) + r"/alte-[0-9]{1,9}-[0-9a-f]{12}/codex-home"
    if not re.fullmatch(pattern, candidate):
        _fail("descriptor_invalid")
    return candidate


def _read_validated_config(candidate, workspace_root, expected_uid):
    components = candidate[1:].split("/")
    workspace_components = workspace_root[1:].split("/")
    if components[:len(workspace_components)] != workspace_components:
        _fail("descriptor_invalid")
    directory_flags = os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC | os.O_NOFOLLOW
    file_flags = os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW | os.O_NONBLOCK
    fds = []
    initial = []
    try:
        try:
            fds.append(os.open("/", directory_flags))
            initial.append(os.fstat(fds[-1]))
            for index, component in enumerate(components):
                fd = os.open(component, directory_flags, dir_fd=fds[-1])
                info = os.fstat(fd)
                if not stat.S_ISDIR(info.st_mode):
                    os.close(fd)
                    _fail("descriptor_invalid")
                if index + 1 >= len(workspace_components):
                    if info.st_uid != expected_uid or stat.S_IMODE(info.st_mode) & 0o022:
                        os.close(fd)
                        _fail("descriptor_invalid")
                fds.append(fd)
                initial.append(info)
        except (OSError, ValueError):
            _fail("descriptor_invalid")

        try:
            config_fd = os.open("config.toml", file_flags, dir_fd=fds[-1])
        except OSError:
            _fail("config_metadata_invalid")
        try:
            before = os.fstat(config_fd)
            if (not stat.S_ISREG(before.st_mode) or before.st_uid != expected_uid or
                    stat.S_IMODE(before.st_mode) != 0o600 or before.st_nlink != 1 or
                    before.st_size > MAX_CONFIG_BYTES):
                _fail("config_metadata_invalid")
            data = _read_all(config_fd)
            after = os.fstat(config_fd)
            if _identity(after) != _identity(before) or len(data) != before.st_size:
                _fail("descriptor_race")

            for fd, expected_info in zip(fds, initial):
                if _identity(os.fstat(fd)) != _identity(expected_info):
                    _fail("descriptor_race")
            for index, component in enumerate(components):
                try:
                    reopened = os.open(component, directory_flags, dir_fd=fds[index])
                except OSError:
                    _fail("descriptor_race")
                try:
                    if _identity(os.fstat(reopened)) != _identity(initial[index + 1]):
                        _fail("descriptor_race")
                finally:
                    os.close(reopened)
            try:
                reopened = os.open("config.toml", file_flags, dir_fd=fds[-1])
            except OSError:
                _fail("descriptor_race")
            try:
                if _identity(os.fstat(reopened)) != _identity(before):
                    _fail("descriptor_race")
            finally:
                os.close(reopened)
            return data
        finally:
            os.close(config_fd)
    finally:
        for fd in reversed(fds):
            os.close(fd)


def _base_line_without_comment(line):
    state = "normal"
    escaped = False
    for index, character in enumerate(line):
        if state == "basic":
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == '"':
                state = "normal"
        elif state == "literal":
            if character == "'":
                state = "normal"
        elif character == '"':
            state = "basic"
        elif character == "'":
            state = "literal"
        elif character == "#":
            return line[:index]
    if state != "normal" or escaped:
        _fail("base_policy_invalid")
    return line


def _base_key_path(raw):
    position = 0
    parts = []
    while True:
        while position < len(raw) and raw[position] in " \t":
            position += 1
        if position >= len(raw):
            _fail("base_policy_invalid")
        quote = raw[position] if raw[position] in "\"'" else None
        if quote is not None:
            position += 1
            start = position
            while position < len(raw) and raw[position] != quote:
                if raw[position] == "\\" or ord(raw[position]) < 32:
                    _fail("base_policy_invalid")
                position += 1
            if position >= len(raw) or position == start:
                _fail("base_policy_invalid")
            parts.append(raw[start:position])
            position += 1
        else:
            match = _BARE_KEY.match(raw, position)
            if not match:
                _fail("base_policy_invalid")
            parts.append(match.group(0))
            position = match.end()
        while position < len(raw) and raw[position] in " \t":
            position += 1
        if position == len(raw):
            return parts
        if raw[position] != ".":
            _fail("base_policy_invalid")
        position += 1


def _reject_base_mcp_authority(text):
    if '"""' in text or "'''" in text:
        _fail("base_policy_invalid")
    for raw_line in text.splitlines():
        line = _base_line_without_comment(raw_line).strip()
        if not line:
            continue
        if line.startswith("[["):
            if not line.endswith("]]"):
                _fail("base_policy_invalid")
            key_path = _base_key_path(line[2:-2])
        elif line.startswith("["):
            if not line.endswith("]"):
                _fail("base_policy_invalid")
            key_path = _base_key_path(line[1:-1])
        else:
            state = "normal"
            escaped = False
            separator = None
            for index, character in enumerate(line):
                if state == "basic":
                    if escaped:
                        escaped = False
                    elif character == "\\":
                        escaped = True
                    elif character == '"':
                        state = "normal"
                elif state == "literal":
                    if character == "'":
                        state = "normal"
                elif character == '"':
                    state = "basic"
                elif character == "'":
                    state = "literal"
                elif character == "=":
                    separator = index
                    break
            if separator is None:
                _fail("base_policy_invalid")
            key_path = _base_key_path(line[:separator])
        if key_path[0] == "mcp_servers":
            _fail("base_policy_invalid")


def _read_base_policy(path, expected_sha256):
    if not isinstance(expected_sha256, str) or not re.fullmatch(r"[0-9a-f]{64}", expected_sha256):
        _fail("base_policy_digest_mismatch")
    if (not isinstance(path, str) or "\x00" in path or not path.startswith("/") or
            os.path.normpath(path) != path):
        _fail("base_policy_invalid")
    try:
        info = os.lstat(path)
        if not stat.S_ISREG(info.st_mode):
            _fail("base_policy_invalid")
        fd = os.open(path, os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW)
    except OSError:
        _fail("base_policy_invalid")
    try:
        data = _read_all(fd)
        if _identity(os.fstat(fd)) != _identity(info):
            _fail("base_policy_invalid")
    finally:
        os.close(fd)
    if _digest(data) != expected_sha256:
        _fail("base_policy_digest_mismatch")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        _fail("base_policy_invalid")
    if (b"\x00" in data or b"\r" in data or data.startswith(b"\xef\xbb\xbf") or
            BEGIN_MARKER.encode() in data or END_MARKER.encode() in data or
            (data and not data.endswith(b"\n"))):
        _fail("base_policy_invalid")
    _reject_base_mcp_authority(text)
    return data


def _directory_identity(info):
    return (info.st_dev, info.st_ino, stat.S_IFMT(info.st_mode), stat.S_IMODE(info.st_mode),
            info.st_uid, info.st_gid)


def _check_output_directory(path, directory_fd, expected_identity, expected_uid):
    try:
        named = os.lstat(path)
        held = os.fstat(directory_fd)
    except OSError:
        _fail("output_invalid")
    if (_identity(named) != _identity(held) or _directory_identity(held) != expected_identity or
            not stat.S_ISDIR(held.st_mode) or stat.S_ISLNK(named.st_mode) or
            held.st_uid != expected_uid or stat.S_IMODE(held.st_mode) != 0o700):
        _fail("output_invalid")


def _open_output_directory(path, expected_uid):
    if (not isinstance(path, str) or "\x00" in path or not path.startswith("/") or
            os.path.normpath(path) != path):
        _fail("output_invalid")
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC | os.O_NOFOLLOW
    directory_fd = None
    try:
        named = os.lstat(path)
        directory_fd = os.open(path, flags)
        held = os.fstat(directory_fd)
    except OSError:
        if directory_fd is not None:
            os.close(directory_fd)
        _fail("output_invalid")
    identity = _directory_identity(held)
    try:
        if (_identity(named) != _identity(held) or not stat.S_ISDIR(held.st_mode) or
                stat.S_ISLNK(named.st_mode) or held.st_uid != expected_uid or
                stat.S_IMODE(held.st_mode) != 0o700):
            _fail("output_invalid")
        for name in ("codex-config.toml", "codex-mcp-catalog.json"):
            try:
                os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
            except FileNotFoundError:
                continue
            except OSError:
                _fail("output_invalid")
            _fail("output_exists")
        return directory_fd, identity
    except MappingError:
        os.close(directory_fd)
        raise


def _unlink_bound_entry(directory_fd, name, expected_inode):
    try:
        current = os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
    except FileNotFoundError:
        return False
    except OSError:
        return False
    if _inode_identity(current) != expected_inode:
        return False
    try:
        os.unlink(name, dir_fd=directory_fd)
    except OSError:
        return False
    return True


def _read_published(fd, expected_size):
    chunks = []
    remaining = expected_size + 1
    while remaining:
        chunk = os.read(fd, min(8192, remaining))
        if not chunk:
            break
        chunks.append(chunk)
        remaining -= len(chunk)
    return b"".join(chunks)


def _write_atomic(directory, directory_fd, directory_identity, name, data, expected_uid):
    temporary = ".%s.%s.tmp" % (name, uuid.uuid4().hex)
    final_path = os.path.join(directory, name)
    fd = None
    temporary_inode = None
    linked_inode = None
    link_created = False
    completed = False
    try:
        _check_output_directory(directory, directory_fd, directory_identity, expected_uid)
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_CLOEXEC | os.O_NOFOLLOW,
                     0o600, dir_fd=directory_fd)
        offset = 0
        while offset < len(data):
            written = os.write(fd, data[offset:])
            if written <= 0:
                _fail("output_invalid")
            offset += written
        os.fchmod(fd, 0o600)
        os.fsync(fd)
        before = os.fstat(fd)
        if (not stat.S_ISREG(before.st_mode) or before.st_uid != expected_uid or
                stat.S_IMODE(before.st_mode) != 0o600 or before.st_nlink != 1 or
                before.st_size != len(data)):
            _fail("output_invalid")
        temporary_inode = _inode_identity(before)
        named_temporary = os.stat(temporary, dir_fd=directory_fd, follow_symlinks=False)
        if _identity(named_temporary) != _identity(before):
            _fail("output_invalid")
        try:
            os.link(temporary, name, src_dir_fd=directory_fd, dst_dir_fd=directory_fd,
                    follow_symlinks=False)
        except FileExistsError:
            _fail("output_exists")
        link_created = True
        final_after_link = os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
        linked_inode = _inode_identity(final_after_link)
        held_after_link = os.fstat(fd)
        temporary_after_link = os.stat(temporary, dir_fd=directory_fd, follow_symlinks=False)
        if (temporary_inode != _inode_identity(held_after_link) or
                temporary_inode != _inode_identity(temporary_after_link) or
                temporary_inode != linked_inode or held_after_link.st_nlink != 2 or
                _identity(held_after_link) != _identity(temporary_after_link) or
                _identity(held_after_link) != _identity(final_after_link)):
            _fail("output_invalid")
        if not _unlink_bound_entry(directory_fd, temporary, temporary_inode):
            _fail("output_invalid")
        temporary_inode = None
        held_after_unlink = os.fstat(fd)
        final_after_unlink = os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
        if (_inode_identity(held_after_unlink) != linked_inode or
                _inode_identity(final_after_unlink) != linked_inode or
                held_after_unlink.st_nlink != 1 or final_after_unlink.st_nlink != 1 or
                _identity(held_after_unlink) != _identity(final_after_unlink)):
            _fail("output_invalid")
        os.fsync(directory_fd)
        _check_output_directory(directory, directory_fd, directory_identity, expected_uid)
        final_fd = os.open(
            name, os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW | os.O_NONBLOCK,
            dir_fd=directory_fd)
        try:
            final_before_read = os.fstat(final_fd)
            held_before_read = os.fstat(fd)
            if (not stat.S_ISREG(final_before_read.st_mode) or
                    final_before_read.st_uid != expected_uid or
                    stat.S_IMODE(final_before_read.st_mode) != 0o600 or
                    final_before_read.st_nlink != 1 or final_before_read.st_size != len(data) or
                    _inode_identity(final_before_read) != linked_inode or
                    _identity(final_before_read) != _identity(held_before_read)):
                _fail("output_invalid")
            published = _read_published(final_fd, len(data))
            final_after_read = os.fstat(final_fd)
            held_after_read = os.fstat(fd)
            named_final = os.stat(name, dir_fd=directory_fd, follow_symlinks=False)
            if (_inode_identity(final_before_read) != linked_inode or
                    _identity(final_before_read) != _identity(final_after_read) or
                    _identity(final_after_read) != _identity(held_after_read) or
                    _identity(final_after_read) != _identity(named_final) or
                    final_after_read.st_nlink != 1 or published != data):
                _fail("output_invalid")
        finally:
            os.close(final_fd)
        _check_output_directory(directory, directory_fd, directory_identity, expected_uid)
        completed = True
        return final_path, linked_inode
    except MappingError:
        raise
    except OSError:
        _fail("output_invalid")
    finally:
        if temporary_inode is not None:
            _unlink_bound_entry(directory_fd, temporary, temporary_inode)
        if link_created and not completed:
            cleanup_inode = linked_inode if linked_inode is not None else temporary_inode
            if cleanup_inode is not None:
                _unlink_bound_entry(directory_fd, name, cleanup_inode)
        if fd is not None:
            os.close(fd)


def materialize(d2_record, *, workspace_root, expected_cwd, expected_uid,
                base_policy_path, expected_base_sha256, output_dir,
                mapping_policy_version, required_servers=(), playwright=None):
    """Validate, map, and exclusively publish one secret-free policy generation."""
    candidate = _validate_descriptor(d2_record, workspace_root, expected_cwd, expected_uid)
    output_fd, output_identity = _open_output_directory(output_dir, expected_uid)
    try:
        base_policy = _read_base_policy(base_policy_path, expected_base_sha256)
        config = _read_validated_config(candidate, workspace_root, expected_uid)
        plan = build_mapping(config, mapping_policy_version, required_servers, playwright=playwright)
        if plan["failure"] is not None:
            _fail(plan["failure"])
        policy = base_policy + plan["policy_block"]
        created = []
        try:
            catalog_path, catalog_inode = _write_atomic(
                output_dir, output_fd, output_identity, "codex-mcp-catalog.json",
                plan["catalog_json"], expected_uid)
            created.append(("codex-mcp-catalog.json", catalog_inode))
            policy_path, policy_inode = _write_atomic(
                output_dir, output_fd, output_identity, "codex-config.toml", policy, expected_uid)
            created.append(("codex-config.toml", policy_inode))
        except MappingError:
            for name, inode in created:
                _unlink_bound_entry(output_fd, name, inode)
            try:
                os.fsync(output_fd)
            except OSError:
                pass
            raise
        _check_output_directory(output_dir, output_fd, output_identity, expected_uid)
    finally:
        os.close(output_fd)
    return {
        "schema": SCHEMA,
        "managed_mapping_verified": True,
        "catalog_sha256": plan["catalog_sha256"],
        "mapping_digest": plan["mapping_digest"],
        "policy_sha256": _digest(policy),
        "catalog_path": catalog_path,
        "policy_path": policy_path,
        "path_map": plan["path_map"],
    }
