def read_playwright_attestation(reference):
    """Только coordinator receipt с внешним digest; никаких caller readiness booleans."""
    try:
        if not isinstance(reference, dict) or set(reference) != {"path", "sha256", "image"}:
            _fail("playwright_attestation_invalid")
        path = Path(reference["path"])
        if (not path.is_absolute() or str(path.resolve(strict=True)) != str(path) or
                not re.fullmatch(r"[a-f0-9]{64}", reference["sha256"]) or
                not re.fullmatch(r"sha256:[a-f0-9]{64}", reference["image"])):
            _fail("playwright_attestation_invalid")
        parent = path.parent.lstat()
        before = path.lstat()
        if (not stat.S_ISDIR(parent.st_mode) or stat.S_IMODE(parent.st_mode) != 0o700 or
                parent.st_uid != os.getuid() or not stat.S_ISREG(before.st_mode) or
                stat.S_IMODE(before.st_mode) != 0o600 or before.st_uid != os.getuid() or
                before.st_nlink != 1 or not 0 < before.st_size <= MAX_CATALOG_BYTES):
            _fail("playwright_attestation_invalid")
        fd = os.open(str(path), os.O_RDONLY | os.O_CLOEXEC | os.O_NOFOLLOW | os.O_NONBLOCK)
        try:
            if _identity(os.fstat(fd)) != _identity(before):
                _fail("playwright_attestation_invalid")
            data = _read_all(fd)
            if (_identity(os.fstat(fd)) != _identity(before) or _identity(path.lstat()) != _identity(before) or
                    _identity(path.parent.lstat()) != _identity(parent)):
                _fail("playwright_attestation_invalid")
        finally:
            os.close(fd)
        if _digest(data) != reference["sha256"]:
            _fail("playwright_attestation_invalid")
        record = json.loads(data)
        expected = playwright_receipt_template(reference["image"])
        if (not isinstance(record, dict) or set(record) != set(expected) or _canonical_json(record) != data or
                any(record[key] != value for key, value in expected.items() if key not in ("artifacts", "checks"))):
            _fail("playwright_attestation_invalid")
        for key, names in (("artifacts", PLAYWRIGHT_ARTIFACTS), ("checks", PLAYWRIGHT_CHECKS)):
            if (not isinstance(record[key], dict) or set(record[key]) != set(names) or
                    any(not isinstance(v, str) or not re.fullmatch(r"[a-f0-9]{64}", v) for v in record[key].values())):
                _fail("playwright_attestation_invalid")
        return record
    except (OSError, TypeError, ValueError, KeyError):
        _fail("playwright_attestation_invalid")


class MappingError(ValueError):
    """A fixed, non-disclosing mapper failure."""

    def __init__(self, code):
        super().__init__(code)
        self.code = code


def _fail(code):
    raise MappingError(code) from None


def _digest(data):
    return hashlib.sha256(data).hexdigest()


def _canonical_json(value):
    encoded = (json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True) + "\n").encode()
    if len(encoded) > MAX_CATALOG_BYTES:
        _fail("input_bound_exceeded")
    return encoded


def _decode_config(data):
    if not isinstance(data, bytes) or len(data) > MAX_CONFIG_BYTES:
        _fail("input_bound_exceeded")
    if data.startswith(b"\xef\xbb\xbf") or b"\x00" in data or b"\r" in data:
        _fail("config_encoding_invalid")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        _fail("config_encoding_invalid")
    if (any(ord(character) < 32 and character not in "\t\n" for character in text) or
            any(character in "\u0085\u2028\u2029" for character in text)):
        _fail("config_encoding_invalid")
    return text


def _lexical_markers(text, *, multiline_prefix=False):
    if '\"\"\"' in text or "'''" in text:
        _fail("managed_block_ambiguous")

    recognized = []
    lines = text.splitlines()
    square = 0
    curly = 0
    for line_number, line in enumerate(lines):
        if line in (BEGIN_MARKER, END_MARKER):
            if square or curly:
                _fail("managed_block_ambiguous")
            recognized.append((line_number, line))
            continue
        state = "normal"
        escaped = False
        for character in line:
            if state == "comment":
                break
            if state == "basic":
                if escaped:
                    escaped = False
                elif character == "\\":
                    escaped = True
                elif character == '"':
                    state = "normal"
                continue
            if state == "literal":
                if character == "'":
                    state = "normal"
                continue
            if character == "#":
                state = "comment"
            elif character == '"':
                state = "basic"
            elif character == "'":
                state = "literal"
            elif character == "[":
                square += 1
            elif character == "]":
                square -= 1
            elif character == "{":
                curly += 1
            elif character == "}":
                curly -= 1
            if square < 0 or curly < 0:
                _fail("managed_block_ambiguous")
        if (state in ("basic", "literal") or escaped or curly or
                (square and (not multiline_prefix or recognized))):
            _fail("managed_block_ambiguous")

    if square or curly:
        _fail("managed_block_ambiguous")

    raw_begin = text.count(BEGIN_MARKER)
    raw_end = text.count(END_MARKER)
    if not recognized and raw_begin == 0 and raw_end == 0:
        return None
    if raw_begin != 1 or raw_end != 1 or len(recognized) != 2:
        _fail("managed_block_invalid")
    if recognized[0][1] != BEGIN_MARKER or recognized[1][1] != END_MARKER:
        _fail("managed_block_invalid")
    begin_index, end_index = recognized[0][0], recognized[1][0]
    if begin_index >= end_index:
        _fail("managed_block_invalid")
    nonblank = [index for index, line in enumerate(lines) if line.strip()]
    if not text.endswith("\n") or not nonblank or nonblank[-1] != end_index:
        _fail("managed_block_invalid")
    return lines[begin_index + 1:end_index]


class _ValueParser:
    def __init__(self, value):
        self.value = value
        self.position = 0

    def parse(self):
        result = self._value(1)
        self._spaces()
        if self.position != len(self.value):
            _fail("managed_value_invalid")
        return result

    def _spaces(self):
        while self.position < len(self.value) and self.value[self.position] in " \t":
            self.position += 1

    def _value(self, depth):
        if depth > MAX_DEPTH:
            _fail("input_bound_exceeded")
        self._spaces()
        if self.position >= len(self.value):
            _fail("managed_value_invalid")
        current = self.value[self.position]
        if current == '"':
            return self._string()
        if current == "[":
            return self._array(depth)
        if current == "{":
            return self._inline_table(depth)
        for literal, result in (("true", True), ("false", False)):
            if self.value.startswith(literal, self.position):
                self.position += len(literal)
                return result
        match = _NUMBER.match(self.value, self.position)
        if not match:
            _fail("managed_value_invalid")
        token = match.group(0)
        self.position = match.end()
        try:
            if "." in token or "e" in token.lower():
                number = float(token)
                if not math.isfinite(number):
                    _fail("managed_value_invalid")
                return number
            return int(token)
        except (OverflowError, ValueError):
            _fail("managed_value_invalid")

    def _string(self):
        self.position += 1
        pieces = []
        escapes = {"b": "\b", "t": "\t", "n": "\n", "f": "\f", "r": "\r", '"': '"', "\\": "\\"}
        while self.position < len(self.value):
            character = self.value[self.position]
            self.position += 1
            if character == '"':
                decoded = "".join(pieces)
                try:
                    size = len(decoded.encode("utf-8"))
                except UnicodeEncodeError:
                    _fail("managed_value_invalid")
                if size > MAX_STRING_BYTES:
                    _fail("input_bound_exceeded")
                return decoded
            if character == "\\":
                if self.position >= len(self.value):
                    _fail("managed_value_invalid")
                escape = self.value[self.position]
                self.position += 1
                if escape in escapes:
                    pieces.append(escapes[escape])
                    continue
                if escape in ("u", "U"):
                    width = 4 if escape == "u" else 8
                    raw = self.value[self.position:self.position + width]
                    if len(raw) != width or not re.fullmatch(r"[0-9A-Fa-f]+", raw):
                        _fail("managed_value_invalid")
                    self.position += width
                    try:
                        character = chr(int(raw, 16))
                        character.encode("utf-8")
                    except (ValueError, UnicodeEncodeError):
                        _fail("managed_value_invalid")
                    pieces.append(character)
                    continue
                _fail("managed_value_invalid")
            elif ord(character) < 32:
                _fail("managed_value_invalid")
            else:
                pieces.append(character)
        _fail("managed_value_invalid")

    def _array(self, depth):
        self.position += 1
        result = []
        self._spaces()
        if self.position < len(self.value) and self.value[self.position] == "]":
            self.position += 1
            return result
        while True:
            result.append(self._value(depth + 1))
            self._spaces()
            if self.position >= len(self.value):
                _fail("managed_value_invalid")
            if self.value[self.position] == "]":
                self.position += 1
                return result
            if self.value[self.position] != ",":
                _fail("managed_value_invalid")
            self.position += 1
            self._spaces()
            if self.position >= len(self.value) or self.value[self.position] == "]":
                _fail("managed_value_invalid")

    def _inline_table(self, depth):
        self.position += 1
        result = {}
        self._spaces()
        if self.position < len(self.value) and self.value[self.position] == "}":
            self.position += 1
            return result
        while True:
            match = _BARE_KEY.match(self.value, self.position)
            if not match:
                _fail("managed_value_invalid")
            key = match.group(0)
            self.position = match.end()
            if not self.value.startswith(" = ", self.position) or key in result:
                _fail("managed_value_invalid")
            self.position += 3
            result[key] = self._value(depth + 1)
            self._spaces()
            if self.position >= len(self.value):
                _fail("managed_value_invalid")
            if self.value[self.position] == "}":
                self.position += 1
                return result
            if self.value[self.position] != ",":
                _fail("managed_value_invalid")
            self.position += 1
            self._spaces()
            if self.position >= len(self.value) or self.value[self.position] == "}":
                _fail("managed_value_invalid")


def _parse_managed(data, *, selected_policy=False):
    text = _decode_config(data)
    lines = _lexical_markers(text, multiline_prefix=selected_policy)
    if lines is None:
        return None
    tables = {}
    current = None
    for line in lines:
        if not line:
            continue
        table = re.fullmatch(r"\[mcp_servers\.([A-Za-z0-9_-]+)\]", line)
        if table:
            current = table.group(1)
            if current in tables or len(tables) >= (32 if selected_policy else 3):
                _fail("managed_block_invalid")
            tables[current] = {}
            continue
        assignment = re.fullmatch(r"([A-Za-z0-9_-]+) = (.+)", line)
        if not assignment or current is None:
            _fail("managed_value_invalid")
        key, raw_value = assignment.groups()
        if key in tables[current]:
            _fail("managed_value_invalid")
        tables[current][key] = _ValueParser(raw_value).parse()
    return tables


