mapper = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(mapper)


BEGIN = "# BEGIN multica-managed mcp_servers (do not edit; regenerated by daemon)"
END = "# END multica-managed mcp_servers"
BASE_POLICY = b'model = "gpt-5.6-terra"\nmodel_reasoning_effort = "medium"\n'


def managed(*lines):
    return ("\n".join((BEGIN,) + lines + (END,)) + "\n").encode()


class MappingFixture:
    def __init__(self):
        self.temp = tempfile.TemporaryDirectory(prefix="altera-codex-map-", dir="/private/tmp")
        self.root = Path(self.temp.name)
        self.workspace = self.root / "workspace"
        self.home = self.workspace / "alte-1-012345abcdef" / "codex-home"
        self.home.mkdir(parents=True)
        os.chmod(self.workspace, 0o755)
        os.chmod(self.home.parent, 0o755)
        os.chmod(self.home, 0o755)
        self.config = self.home / "config.toml"
        self.base = self.root / "base.toml"
        self.base.write_bytes(BASE_POLICY)
        os.chmod(self.base, 0o600)
        self.output = self.root / "generation"
        self.output.mkdir(mode=0o700)
        self.uid = os.getuid()

    def close(self):
        self.temp.cleanup()

    def write_config(self, data):
        self.config.write_bytes(data)
        os.chmod(self.config, 0o600)

    def record(self, candidate=None, **overrides):
        descriptor = {
            "candidate_path": str(candidate or self.home),
            "source_sha256": mapper.D2_SOURCE_SHA256,
            "build_sha256": mapper.D2_BUILD_SHA256,
            "read_status": "lexical_candidate",
            "canonical_identity": "not_checked",
            "task_acceptance": "not_checked",
            "cwd_matches_expected": True,
            "argc": 4,
        }
        descriptor.update(overrides)
        return {"binary_sha256": mapper.D2_BINARY_SHA256, "descriptor": descriptor}

    def materialize(self, data, required=(), record=None, **kwargs):
        self.write_config(data)
        return mapper.materialize(
            record or self.record(),
            workspace_root=str(self.workspace),
            expected_cwd=os.getcwd(),
            expected_uid=self.uid,
            base_policy_path=str(self.base),
            expected_base_sha256=hashlib.sha256(BASE_POLICY).hexdigest(),
            output_dir=str(self.output),
            mapping_policy_version="codex-mcp-map-v1",
            required_servers=required,
            **kwargs,
        )


