        os.chmod(auth, 0o600)
        before = {path.name: (path.read_bytes(), path.stat().st_mode) for path in (agents, auth)}
        opened = []
        real_open = mapper.os.open

        def recording_open(path, *args, **kwargs):
            opened.append(os.fspath(path))
            return real_open(path, *args, **kwargs)

        with mock.patch.object(mapper.os, "open", recording_open):
            self.fixture.materialize(managed())
        self.assertNotIn("auth.json", opened)
        self.assertNotIn("AGENTS.md", opened)
        after = {path.name: (path.read_bytes(), path.stat().st_mode) for path in (agents, auth)}
        self.assertEqual(after, before)
        combined = b"".join(path.read_bytes() for path in self.fixture.output.iterdir())
        self.assertNotIn(b"AUTH_SECRET_CANARY", combined)
        self.assertNotIn(b"AGENTS_CONTEXT_CANARY", combined)
